"""Generate a SYNTHETIC per-contract Medicare Advantage prior-authorization
dataset, calibrated to match real, cited aggregate statistics only.

Real, cited aggregate figures being matched (NOT scraped, NOT fabricated
per-contract data — see README.md for full source list and dates):
    - 61 reporting contracts
    - Denial-rate range across contracts: 1.9% - 24.6%
    - Aggregate appeal-overturn rate: 94.6%
  Source: Healthcare Dive reporting on Centene Corporation's CMS-0057-F
  CY2025 public disclosures, as aggregated by AuthDenied (2026).

Everything else in this file (which state a contract sits in, its plan
type, its exact denial rate within the cited range, appeal volumes) is
synthetic and generated by a seeded RNG. It is a plausible reconstruction
for demonstration purposes, not real Centene data.

Run: python3 data/generate_dataset.py
Output: data/contracts.json (committed to the repo)
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd

SEED = 2026
N_CONTRACTS = 61
MIN_DENIAL_RATE = 1.9
MAX_DENIAL_RATE = 24.6
TARGET_OVERTURN_RATE = 94.6

STATES = [
    "AL", "AK", "AZ", "AR", "CA", "CO", "CT", "DE", "DC", "FL",
    "GA", "HI", "ID", "IL", "IN", "IA", "KS", "KY", "LA", "ME",
    "MD", "MA", "MI", "MN", "MS", "MO", "MT", "NE", "NV", "NH",
    "NJ", "NM", "NY", "NC", "ND", "OH", "OK", "OR", "PA", "RI",
    "SC", "SD", "TN", "TX", "UT", "VT", "VA", "WA", "WV", "WI", "WY",
]

PLAN_TYPES = ["HMO", "PPO", "SNP"]
PLAN_TYPE_WEIGHTS = [0.55, 0.30, 0.15]


def generate_denial_rates(rng: np.random.Generator, n: int) -> np.ndarray:
    """Right-skewed synthetic denial rates rescaled onto the cited real range."""
    raw = rng.beta(2, 5, size=n)
    argmin_raw = int(np.argmin(raw))
    argmax_raw = int(np.argmax(raw))
    scaled = MIN_DENIAL_RATE + (raw - raw.min()) / (raw.max() - raw.min()) * (
        MAX_DENIAL_RATE - MIN_DENIAL_RATE
    )
    rates = np.round(scaled, 1)
    # Force the endpoints exactly onto the cited real min/max, guarding
    # against any floating-point rounding drift at the boundary.
    rates[argmin_raw] = MIN_DENIAL_RATE
    rates[argmax_raw] = MAX_DENIAL_RATE
    return rates


def generate_appeal_counts(rng: np.random.Generator, n: int, filed: np.ndarray) -> np.ndarray:
    """Per-contract overturn counts, nudged so the aggregate rate matches 94.6%."""
    per_contract_rate = np.clip(rng.normal(TARGET_OVERTURN_RATE, 3.0, size=n), 0, 100)
    overturned = np.round(filed * per_contract_rate / 100).astype(int)
    overturned = np.minimum(overturned, filed)

    total_filed = int(filed.sum())
    target_overturned = round(total_filed * TARGET_OVERTURN_RATE / 100)
    diff = target_overturned - int(overturned.sum())

    # Apply the whole remainder to the highest-volume contract so the
    # published aggregate overturn rate rounds to exactly 94.6%.
    adjust_idx = int(np.argmax(filed))
    overturned[adjust_idx] = int(np.clip(overturned[adjust_idx] + diff, 0, filed[adjust_idx]))
    return overturned


def main() -> None:
    rng = np.random.default_rng(SEED)

    contract_ids = [f"SYN-{i:03d}" for i in range(1, N_CONTRACTS + 1)]
    states = rng.choice(STATES, size=N_CONTRACTS, replace=True)
    plan_types = rng.choice(PLAN_TYPES, size=N_CONTRACTS, replace=True, p=PLAN_TYPE_WEIGHTS)
    denial_rates = generate_denial_rates(rng, N_CONTRACTS)
    appeals_filed = rng.integers(80, 3500, size=N_CONTRACTS)
    appeals_overturned = generate_appeal_counts(rng, N_CONTRACTS, appeals_filed)

    df = pd.DataFrame(
        {
            "contract_id": contract_ids,
            "state": states,
            "plan_type": plan_types,
            "denial_rate": denial_rates,
            "appeals_filed": appeals_filed,
            "appeals_overturned": appeals_overturned,
        }
    )

    total_filed = int(df["appeals_filed"].sum())
    total_overturned = int(df["appeals_overturned"].sum())
    aggregate_overturn_rate = round(total_overturned / total_filed * 100, 1)

    print(f"contracts: {len(df)}")
    print(f"denial_rate min/max: {df['denial_rate'].min()} / {df['denial_rate'].max()}")
    print(f"aggregate overturn rate: {aggregate_overturn_rate}%")

    assert len(df) == N_CONTRACTS
    assert df["denial_rate"].min() == MIN_DENIAL_RATE
    assert df["denial_rate"].max() == MAX_DENIAL_RATE
    assert aggregate_overturn_rate == TARGET_OVERTURN_RATE

    output = {
        "meta": {
            "synthetic": True,
            "description": (
                "SYNTHETIC per-contract dataset. Only the aggregate figures "
                "below (contract count, denial-rate range, overturn rate) are "
                "real and cited; every per-contract row is generated by a "
                "seeded RNG and does not represent actual Centene disclosures."
            ),
            "seed": SEED,
            "calibration_targets": {
                "n_contracts": N_CONTRACTS,
                "denial_rate_range": [MIN_DENIAL_RATE, MAX_DENIAL_RATE],
                "aggregate_overturn_rate": TARGET_OVERTURN_RATE,
            },
            "real_cited_source": (
                "Healthcare Dive reporting on Centene Corporation CY2025 "
                "CMS-0057-F public disclosures, as aggregated by AuthDenied (2026)."
            ),
        },
        "contracts": json.loads(df.to_json(orient="records")),
    }

    out_path = Path(__file__).parent / "contracts.json"
    out_path.write_text(json.dumps(output, indent=2) + "\n")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
